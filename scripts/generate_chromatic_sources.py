"""Validate explicit public source configuration and emit a no_std static registry."""
import argparse
import ipaddress
import json
import re
from pathlib import Path
from urllib.parse import urlsplit
ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / 'devices/chromatic/sources.json'
OUTPUT = ROOT / 'crates/chromatic-client/src/sources.rs'
def public_dns_name(host):
    # Reject single-label LAN names and inet_aton-style decimal/octal/hex IPs.
    # A DNS-looking name still needs reviewed resolution policy on the device.
    labels = host.split('.')
    return len(labels) >= 2 and all(re.fullmatch(r'[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?', label) for label in labels) and bool(re.fullmatch(r'[a-z]{2,63}|xn--[a-z0-9-]{1,59}', labels[-1]))
def registry(value):
    if set(value) != {'schema_version', 'profiles'} or value['schema_version'] != 1:
        raise ValueError('Unsupported source registry schema')
    profiles = value['profiles']
    if not isinstance(profiles, list) or not 1 <= len(profiles) <= 8:
        raise ValueError('Expected one to eight reviewed public profiles')
    names = set()
    entries, scopes = [], []
    for p in profiles:
        if set(p) != {'name', 'base', 'seed', 'robots', 'scope'} or not all(isinstance(v, str) for v in p.values()):
            raise ValueError('Unexpected profile fields')
        if not re.fullmatch(r'[A-Za-z0-9 _-]{1,24}', p['name']) or p['name'] in names:
            raise ValueError('Profile names must be distinct short ASCII text')
        names.add(p['name'])
        urls = [urlsplit(p[k]) for k in ('base', 'seed', 'robots')]
        for parsed, k in zip(urls, ('base', 'seed', 'robots')):
            host = parsed.hostname or ''
            if parsed.scheme != 'https' or parsed.netloc != host or parsed.query or parsed.fragment or len(p[k]) >= 128 or not public_dns_name(host) or host.endswith(('.local','.localhost','.internal','.test','.invalid')) or '..' in parsed.path or '//' in parsed.path or not re.fullmatch(r'/[A-Za-z0-9/_\-.]*', parsed.path):
                raise ValueError('Only bounded explicit public HTTPS paths are permitted')
            try: ipaddress.ip_address(host)
            except ValueError: pass
            else: raise ValueError('IP literals are not public-source profiles')
        if len({u.netloc for u in urls}) != 1 or not p['base'].endswith('/') or not p['seed'].startswith(p['base']) or urls[2].path != '/robots.txt':
            raise ValueError('Seed and robots must belong to the exact base authority')
        relative = p['seed'][len(p['base']):]
        if p['scope'] == 'node-html':
            if not re.fullmatch(r'node[0-9]{1,2}\.html', relative): raise ValueError('Invalid numbered-page seed')
            scopes.append('true')
        elif p['scope'] == 'html-paths':
            if relative and not relative.endswith(('/', '.html')): raise ValueError('Invalid HTML seed')
            scopes.append('false')
        else: raise ValueError('Unsupported source scope')
        entries.append('    (' + ', '.join(json.dumps(p[k], ensure_ascii=True) for k in ('name','base','seed','robots')) + '),')
    return '// SPDX-License-Identifier: GPL-3.0-only\n// Generated by scripts/generate_chromatic_sources.py; edit devices/chromatic/sources.json.\npub const PROFILES: [(&str, &str, &str, &str); ' + str(len(profiles)) + '] = [\n' + '\n'.join(entries) + '\n];\npub const NUMBERED_SCOPE: [bool; ' + str(len(profiles)) + '] = [' + ', '.join(scopes) + '];\n'
def main():
    args = argparse.ArgumentParser();args.add_argument('--check', action='store_true');opts=args.parse_args()
    text = registry(json.loads(CONFIG.read_text()))
    if opts.check:
        if OUTPUT.read_text() != text: raise SystemExit('Source registry is stale; run scripts/generate_chromatic_sources.py')
    else: OUTPUT.write_text(text)
if __name__ == '__main__': main()
